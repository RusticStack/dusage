#!/usr/bin/env python3
"""Regenerate src/encoding_tables.rs from the WHATWG Encoding Standard.

Usage: gen_encoding_tables.py DIR > src/encoding_tables.rs
DIR holds encodings.json and the single-byte index-*.txt files downloaded from
https://encoding.spec.whatwg.org/ . Run `cargo fmt` on the result.
"""
import json
import os
import sys

sys.stdout.reconfigure(newline="\n")
src = sys.argv[1]
groups = json.load(open(os.path.join(src, "encodings.json"), encoding="utf-8"))
MULTI = {"GBK", "gb18030", "Big5", "EUC-JP", "ISO-2022-JP", "Shift_JIS", "EUC-KR"}
FIXED = {"UTF-8": "Utf8", "UTF-16LE": "Utf16Le", "UTF-16BE": "Utf16Be", "replacement": "Replacement"}

tables, labels = [], []
for g in groups:
    for e in g["encodings"]:
        name = e["name"]
        if name in FIXED:
            kind = f"Label::{FIXED[name]}"
        elif name in MULTI:
            kind = f'Label::Unsupported("{name}")'
        else:
            if name == "x-user-defined":
                cells = [0xF780 + i for i in range(128)]
            else:
                index = "iso-8859-8" if name == "ISO-8859-8-I" else name.lower()
                cells = [0] * 128
                for line in open(os.path.join(src, f"index-{index}.txt"), encoding="utf-8"):
                    line = line.strip()
                    if line and not line.startswith("#"):
                        pointer, cp = line.split("\t")[:2]
                        cells[int(pointer)] = int(cp, 16)
            kind = f"Label::SingleByte({len(tables)})"
            tables.append((name.lower(), cells))
        labels += [(label, kind) for label in e["labels"]]

print("//! Generated by scripts/gen_encoding_tables.py from the WHATWG Encoding Standard")
print("//! (https://encoding.spec.whatwg.org/, encodings.json and the single-byte indexes).")
print("//! Do not edit by hand.")
print()
print("/// What a WHATWG label names.")
print("#[derive(Clone, Copy, Debug, PartialEq, Eq)]")
print("pub enum Label {")
print("    Utf8,")
print("    Utf16Le,")
print("    Utf16Be,")
print("    /// The standard's `replacement` encoding: any input decodes to one U+FFFD.")
print("    Replacement,")
print("    /// An index into [`SINGLE_BYTE`].")
print("    SingleByte(u8),")
print("    /// A multi-byte encoding (by its standard name) that has no decoder here.")
print("    Unsupported(&'static str),")
print("}")
print()
print("/// Every label of the standard, sorted for binary search.")
print(f"pub static LABELS: [(&str, Label); {len(labels)}] = [")
for label, kind in sorted(labels):
    print(f'    ("{label}", {kind}),')
print("];")
print()
print("/// Canonical name and the code points of bytes 0x80..=0xFF; 0 is an unmapped byte.")
print(f"pub static SINGLE_BYTE: [(&str, [u16; 128]); {len(tables)}] = [")
for name, cells in tables:
    print(f'    ("{name}", [')
    for i in range(0, 128, 8):
        print("        " + " ".join(f"0x{c:04X}," for c in cells[i : i + 8]))
    print("    ]),")
print("];")
