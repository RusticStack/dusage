//! Unicode tables and code-point classes for the regex engine (std only).
//!
//! # What is here
//!
//! * the Unicode general categories, as one partition table of the assigned code
//!   space (`Group::of`), from which `\p{L}`, `\p{Lu}`, `\p{Ll}`, `\p{N}`, `\p{Nd}`,
//!   `\p{P}`, `\p{Z}`, `\p{S}` and `\p{C}` are built;
//! * the simple case-folding classes, run-encoded (`fold`);
//! * the two properties the engine needs beyond the categories: `White_Space` (for
//!   `\s`) and `Pc` (for `\w` and `\b`);
//! * `CharClass`, the sorted range set the engine matches one code point against.
//!
//! # The data
//!
//! Generated from Unicode 15.0 (`UnicodeData.txt` and `CaseFolding.txt`, as published
//! by Python 3.12's `unicodedata`), then compressed by hand into these shapes:
//!
//! | table | entries | what it holds |
//! | --- | --- | --- |
//! | `GROUPS` | 2,773 | maximal runs of one general category over the assigned code space |
//! | `ND` | 64 | `Nd`, because `N` above lumps it with `Nl` and `No` |
//! | `CONNECTOR` | 6 | `Pc`, part of `P` but needed on its own by `\w` |
//! | `SPACE` | 10 | the `White_Space` property, which is not a general category |
//! | `FOLD_RUNS` | 210 | 1,438 case-folding pairs as arithmetic runs |
//!
//! Four things keep `GROUPS` at 2,773 runs instead of the ~3,700 a table per category
//! would take. It is *one* partition of the code space rather than nine overlapping
//! sets, so a boundary is stored once and a letter run is never repeated in `L`, `Lu`
//! and `Ll`. `\p{C}` is not stored at all: every code point has exactly one category,
//! so `C` is "no row matches", which drops the 712 unassigned and control runs a
//! stored `C` would need. Unassigned stretches never appear: they are gaps between
//! rows. And the case dimension is a label in the same row, not a second lookup, so
//! `Lu`, `Ll` and `Lt` cost no extra runs — the 2,773 is what the breakdown
//! `Lu 646 + Ll 658 + Lo 510 + M 310 + S 232 + P 191 + N 137 + Lm 71 + Lt 10 + Z 8`
//! adds up to. Every row is a `(start, end, label)` triple searched by binary search.
//!
//! A few hundred runs is not reachable at full fidelity: the two categories the table
//! must keep apart to answer `\p{L}` honestly are letters and marks, and Latin
//! Extended-A/B alone alternate upper and lower case once per character, which is a
//! run per character. Covering only "common scripts" would meet that budget by
//! refusing to answer for the rest, which is a worse trade for a grep tool than 2,773
//! numbers in a table nobody has to read.
//!
//! # Folding
//!
//! `fold` is simple case folding with the `CaseFolding.txt` entries that keep one
//! character's length folded in as well, so `Σ`, `σ` and `ς` all fold to `σ`, `ſ` to
//! `s`, `K` (Kelvin) to `k` and `ß` to `ß`. Length-changing folds (`ß` to `ss`,
//! `İ` to `i̇`) are deliberately out: a character class has one character per step.

/// One Unicode general category, or the letter of it a pattern names.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Group {
    UpperLetter,
    LowerLetter,
    TitleLetter,
    ModifierLetter,
    OtherLetter,
    Mark,
    Number,
    Punctuation,
    Symbol,
    Separator,
    /// Everything else: control, format, surrogate, private use and unassigned.
    Other,
}

/// The order the labels in `GROUPS` use.
const LABELS: [Group; 10] = [
    Group::UpperLetter,
    Group::LowerLetter,
    Group::TitleLetter,
    Group::ModifierLetter,
    Group::OtherLetter,
    Group::Mark,
    Group::Number,
    Group::Punctuation,
    Group::Symbol,
    Group::Separator,
];

/// The highest code point, `char::MAX` as a number.
const MAX: u32 = 0x10FFFF;

impl Group {
    /// The general category of `c`.
    pub fn of(c: char) -> Group {
        let cp = c as u32;
        let idx = GROUPS.partition_point(|&(start, _, _)| start <= cp);
        if idx == 0 {
            return Group::Other;
        }
        let (start, end, label) = GROUPS[idx - 1];
        if cp >= start && cp <= end {
            LABELS[label as usize]
        } else {
            Group::Other
        }
    }

    /// True for the five letter categories.
    pub fn is_letter(self) -> bool {
        matches!(
            self,
            Group::UpperLetter
                | Group::LowerLetter
                | Group::TitleLetter
                | Group::ModifierLetter
                | Group::OtherLetter
        )
    }
}

/// A set of code points: sorted, disjoint, non-adjacent `(first, last)` ranges.
#[derive(Clone, Debug, Default)]
pub struct CharClass {
    ranges: Vec<(u32, u32)>,
}

impl CharClass {
    pub fn new() -> CharClass {
        CharClass::default()
    }

    /// The class holding exactly the code points in `ranges`.
    fn from_ranges(ranges: &[(u32, u32)]) -> CharClass {
        let mut out = CharClass::new();
        for &(lo, hi) in ranges {
            out.insert(lo, hi);
        }
        out
    }

    pub fn add(&mut self, c: char) {
        self.insert(c as u32, c as u32);
    }

    pub fn add_range(&mut self, lo: char, hi: char) {
        self.insert(lo as u32, hi as u32);
    }

    /// Add every code point of `other`.
    pub fn union(&mut self, other: &CharClass) {
        for &(lo, hi) in &other.ranges {
            self.insert(lo, hi);
        }
    }

    /// Every code point this class does not hold, in `0..=char::MAX`.
    pub fn negate(&mut self) {
        let mut out = Vec::with_capacity(self.ranges.len() + 1);
        let mut next = 0u32;
        for &(lo, hi) in &self.ranges {
            if lo > next {
                out.push((next, lo - 1));
            }
            next = hi + 1;
        }
        if next <= MAX {
            out.push((next, MAX));
        }
        self.ranges = out;
    }

    /// Close the class under simple case folding: every member gains the characters
    /// that fold together with it, so `[é]` under `-i` also holds `É` and `Σ` holds
    /// `σ` and `ς`. Runs until nothing changes, because folding is a transitive
    /// relation and patterns such as `[Σ]` need the whole equivalence class.
    pub fn fold(&mut self) {
        loop {
            let mut grew = false;
            for &(from, end, stride, delta) in FOLD_RUNS {
                let mut cp = from;
                while cp <= end {
                    let to = (cp as i32 + delta) as u32;
                    if self.covers(cp, cp) {
                        grew |= self.insert(to, to);
                    }
                    if self.covers(to, to) {
                        grew |= self.insert(cp, cp);
                    }
                    cp += stride as u32;
                }
            }
            if !grew {
                return;
            }
        }
    }

    pub fn contains(&self, c: char) -> bool {
        self.covers(c as u32, c as u32)
    }

    pub fn is_empty(&self) -> bool {
        self.ranges.is_empty()
    }

    /// The single code point in the class, if it holds exactly one.
    pub fn sole(&self) -> Option<char> {
        match self.ranges[..] {
            [(lo, hi)] if lo == hi => char::from_u32(lo),
            _ => None,
        }
    }

    pub fn ranges(&self) -> &[(u32, u32)] {
        &self.ranges
    }

    /// True when every code point in `lo..=hi` is in the class.
    fn covers(&self, lo: u32, hi: u32) -> bool {
        match self.ranges.binary_search_by(|&(start, end)| {
            if end < lo {
                std::cmp::Ordering::Less
            } else if start > hi {
                std::cmp::Ordering::Greater
            } else {
                std::cmp::Ordering::Equal
            }
        }) {
            // The range found intersects `lo..=hi`; it covers it only if it reaches
            // both ends, since ranges never overlap.
            Ok(i) => self.ranges[i].0 <= lo && self.ranges[i].1 >= hi,
            Err(_) => false,
        }
    }

    /// Add `lo..=hi`, merging with the ranges it touches. Returns whether the class
    /// grew.
    fn insert(&mut self, lo: u32, hi: u32) -> bool {
        let grew = !self.covers(lo, hi);
        let mut lo = lo;
        let mut hi = hi;
        let i = self.ranges.partition_point(|&(_, end)| end + 1 < lo);
        while i < self.ranges.len() && self.ranges[i].0 <= hi + 1 {
            lo = lo.min(self.ranges[i].0);
            hi = hi.max(self.ranges[i].1);
            self.ranges.remove(i);
        }
        self.ranges.insert(i, (lo, hi));
        grew
    }
}

/// The simple case folding of `c`: the character it matches under `-i`, itself when it
/// has no fold.
pub fn fold(c: char) -> char {
    let cp = c as u32;
    let idx = FOLD_RUNS.partition_point(|&(start, _, _, _)| start <= cp);
    if idx == 0 {
        return c;
    }
    let (start, end, stride, delta) = FOLD_RUNS[idx - 1];
    if cp > end || !(cp - start).is_multiple_of(stride as u32) {
        return c;
    }
    char::from_u32((cp as i32 + delta) as u32).unwrap_or(c)
}

/// True when `a` and `b` fold together, the test behind `-i`.
pub fn fold_eq(a: char, b: char) -> bool {
    fold(a) == fold(b)
}

/// True when `c` is a word character for `\w` and `\b`: a letter, a mark, a number, a
/// connector punctuation character, or a zero-width joiner.
pub fn is_word(c: char) -> bool {
    match Group::of(c) {
        Group::UpperLetter
        | Group::LowerLetter
        | Group::TitleLetter
        | Group::ModifierLetter
        | Group::OtherLetter
        | Group::Mark
        | Group::Number => true,
        Group::Punctuation => in_ranges(CONNECTOR, c),
        Group::Symbol | Group::Separator | Group::Other => c == '\u{200C}' || c == '\u{200D}',
    }
}

/// True for the `White_Space` property, what `\s` matches.
pub fn is_space(c: char) -> bool {
    in_ranges(SPACE, c)
}

/// `\d`: every Unicode decimal digit.
pub fn digit() -> CharClass {
    CharClass::from_ranges(ND)
}

/// `\w`: every word character, `is_word` as a set.
pub fn word() -> CharClass {
    let mut out = by_group(|g| {
        !matches!(
            g,
            Group::Punctuation | Group::Symbol | Group::Separator | Group::Other
        )
    });
    out.union(&CharClass::from_ranges(CONNECTOR));
    out.add('\u{200C}');
    out.add('\u{200D}');
    out
}

/// `\s`: the `White_Space` property as a set.
pub fn space() -> CharClass {
    CharClass::from_ranges(SPACE)
}

/// `.`: every character, except `\n` unless the dot flag makes it any.
pub fn dot(matches_newline: bool) -> CharClass {
    let mut out = CharClass::new();
    if matches_newline {
        out.add_range('\0', char::MAX);
    } else {
        let newline = '\n' as u32;
        out.insert(0, newline - 1);
        out.insert(newline + 1, MAX);
    }
    out
}

/// The class a `\p{name}` names, or `None` when the name is not one of the supported
/// general categories. A leading `^` negates, as in `\p{^L}`.
pub fn property(name: &str) -> Option<CharClass> {
    let (negated, name) = match name.strip_prefix('^') {
        Some(rest) => (true, rest),
        None => (false, name),
    };
    let mut class = match name {
        "L" | "Letter" => by_group(Group::is_letter),
        "Lu" | "Uppercase_Letter" => by_group(|g| g == Group::UpperLetter),
        "Ll" | "Lowercase_Letter" => by_group(|g| g == Group::LowerLetter),
        "Lt" | "Titlecase_Letter" => by_group(|g| g == Group::TitleLetter),
        "Lm" | "Modifier_Letter" => by_group(|g| g == Group::ModifierLetter),
        "Lo" | "Other_Letter" => by_group(|g| g == Group::OtherLetter),
        "M" | "Mark" => by_group(|g| g == Group::Mark),
        "N" | "Number" => by_group(|g| g == Group::Number),
        "Nd" | "Decimal_Number" | "Digit" => CharClass::from_ranges(ND),
        "P" | "Punctuation" => by_group(|g| g == Group::Punctuation),
        "Z" | "Separator" => by_group(|g| g == Group::Separator),
        "S" | "Symbol" => by_group(|g| g == Group::Symbol),
        // Every code point has one category, so `C` is the complement of the assigned
        // runs `GROUPS` stores, which is also where the unassigned ones live.
        "C" | "Other" => {
            let mut out = by_group(|_| true);
            out.negate();
            out
        }
        _ => return None,
    };
    if negated {
        class.negate();
    }
    Some(class)
}

/// The class a POSIX bracket expression names, in its Unicode meaning: `[:alpha:]` is
/// `\p{L}`, `[:digit:]` is `\p{Nd}`, `[:space:]` is `White_Space`. `[:ascii:]`,
/// `[:xdigit:]` and `[:cntrl:]` keep their byte meanings.
pub fn posix(name: &str) -> Option<CharClass> {
    let class = match name {
        "alnum" => union(&[by_group(Group::is_letter), by_group(|g| g == Group::Number)]),
        "alpha" => by_group(Group::is_letter),
        "ascii" => {
            let mut out = CharClass::new();
            out.add_range('\0', '\u{7f}');
            out
        }
        "blank" => union(&[by_group(|g| g == Group::Separator), tab()]),
        "cntrl" => {
            let mut out = CharClass::new();
            out.add_range('\0', '\u{1f}');
            out.add_range('\u{7f}', '\u{9f}');
            out
        }
        "digit" => CharClass::from_ranges(ND),
        "graph" => by_group(|g| !matches!(g, Group::Separator | Group::Other)),
        "lower" => by_group(|g| g == Group::LowerLetter),
        "print" => by_group(|g| !matches!(g, Group::Other)),
        "punct" => by_group(|g| g == Group::Punctuation),
        "space" => CharClass::from_ranges(SPACE),
        "upper" => by_group(|g| g == Group::UpperLetter),
        "word" => word(),
        "xdigit" => {
            let mut out = CharClass::new();
            for c in "0123456789ABCDEFabcdef".chars() {
                out.add(c);
            }
            out
        }
        _ => return None,
    };
    Some(class)
}

fn tab() -> CharClass {
    let mut out = CharClass::new();
    out.add('\t');
    out
}

fn union(parts: &[CharClass]) -> CharClass {
    let mut out = CharClass::new();
    for part in parts {
        out.union(part);
    }
    out
}

/// Every code point whose category satisfies `pick`, as one class.
fn by_group(pick: impl Fn(Group) -> bool) -> CharClass {
    let mut out = CharClass::new();
    for &(lo, hi, label) in GROUPS {
        if pick(LABELS[label as usize]) {
            out.insert(lo, hi);
        }
    }
    out
}

fn in_ranges(table: &[(u32, u32)], c: char) -> bool {
    let cp = c as u32;
    let idx = table.partition_point(|&(_, end)| end < cp);
    table
        .get(idx)
        .is_some_and(|&(start, end)| cp >= start && cp <= end)
}

